#!/usr/bin/env python
"""Generate llms-full.txt (llmstxt.org convention) at the repository root.

The file is llms.txt, then AGENTS.md, then every repository file that llms.txt
links, in the order llms.txt lists them. Each file starts with a header line.

Left out:

- docs/tools-generated.md (generated, very large): a pointer is written instead.
- CHANGELOG.md (changes with every pull request): a pointer is written instead.
- THIRD_PARTY_NOTICES.md and everything under docs/i18n/.
- llms-full.txt itself, and links that are not files in the repository.

Usage:  python scripts/make_llms_full.py [--check]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "llms-full.txt"
SELF = "llms-full.txt"
LINK_BASE = "https://github.com/Sam-AEC/aec-model-bridge/blob/main/"

POINTERS = {
    "docs/tools-generated.md": "Every tool with its read or write flag. Generated and very large, so it is not copied here.",
    "CHANGELOG.md": "Changes per release. It changes with every pull request, so it is not copied here.",
}
EXCLUDED_FILES = {"THIRD_PARTY_NOTICES.md", SELF}
EXCLUDED_PREFIXES = ("docs/i18n/",)

_LINK = re.compile(r"\]\(" + re.escape(LINK_BASE) + r"([^)#\s]+)")


def read(rel: str) -> str:
    text = (ROOT / rel).read_text(encoding="utf-8")
    return text.replace("\r\n", "\n").replace("\r", "\n").strip("\n")


def excluded(rel: str) -> bool:
    return rel in EXCLUDED_FILES or rel.startswith(EXCLUDED_PREFIXES)


def file_list() -> tuple[list[str], list[str]]:
    """Return ``(files to copy, pointer paths)``, both in stable order."""
    ordered = ["llms.txt", "AGENTS.md"]
    pointers: list[str] = []
    for rel in _LINK.findall(read("llms.txt")):
        if rel in POINTERS:
            if rel not in pointers:
                pointers.append(rel)
            continue
        if excluded(rel) or rel in ordered or not (ROOT / rel).is_file():
            continue
        ordered.append(rel)
    return ordered, pointers


def build() -> str:
    files, pointers = file_list()
    parts = [
        "# AEC Model Bridge: full text",
        "",
        "This file joins llms.txt, AGENTS.md and the docs that llms.txt links, in one file. "
        "It is generated by scripts/make_llms_full.py. Do not edit it by hand. "
        "Each source file starts after a line that begins with `=== FILE:`.",
        "",
        "Files in this document:",
        "",
    ]
    parts += [f"- {rel}" for rel in files]
    if pointers:
        parts += ["", "Not copied (read them from the repository):", ""]
        parts += [f"- {rel}: {POINTERS[rel]}" for rel in pointers]
    for rel in files:
        parts += ["", f"=== FILE: {rel} ===", "", read(rel)]
    return "\n".join(parts) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if llms-full.txt is out of date")
    args = parser.parse_args(argv)
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("llms-full.txt is out of date. Run: python scripts/make_llms_full.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {SELF} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
