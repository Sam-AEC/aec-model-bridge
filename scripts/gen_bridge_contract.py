#!/usr/bin/env python3
"""Generate the Python and C# code for the shared add-in command contract.

Source: contracts/bridge-commands.json. Each command has a name, is_mutating, and params:
a JSON Schema for the payload, or the string "unchecked" when the payload is not described.

Outputs:
  packages/mcp-server-revit/src/revit_mcp_server/bridge/contract_generated.py
      the schemas and validate_command(name, params), called by the bridge client before it sends.
  packages/revit-bridge-addin/src/Bridge/BridgeContract.g.cs
      command name constants and an IsMutating map. Plain C# that builds on net48, net8 and net10.

Usage:  python scripts/gen_bridge_contract.py [--check]
"""
from __future__ import annotations

import argparse
import json
import pprint
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "contracts" / "bridge-commands.json"
PY_OUT = ROOT / "packages" / "mcp-server-revit" / "src" / "revit_mcp_server" / "bridge" / "contract_generated.py"
CS_OUT = ROOT / "packages" / "revit-bridge-addin" / "src" / "Bridge" / "BridgeContract.g.cs"

UNCHECKED = "unchecked"
_NAME = re.compile(r"^[a-z][a-z0-9]*\.[a-z][a-z0-9_]*$")


def load(path: Path = CONTRACT) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    problems = check_contract(data)
    if problems:
        raise SystemExit("contracts/bridge-commands.json is invalid:\n  " + "\n  ".join(problems))
    return data


def check_contract(data: dict) -> list[str]:
    """Structural checks on the contract file itself."""
    problems = []
    if not isinstance(data.get("contract_version"), int):
        problems.append("contract_version must be an integer")
    if not isinstance(data.get("$defs", {}), dict):
        problems.append("$defs must be an object")
    commands = data.get("commands")
    if not isinstance(commands, dict) or not commands:
        return problems + ["commands must be a non-empty object"]
    if list(commands) != sorted(commands):
        problems.append("commands must be sorted by name")
    defs = data.get("$defs", {})
    for name, entry in commands.items():
        if not _NAME.match(name):
            problems.append(f"{name}: name must look like 'revit.create_wall'")
        if not isinstance(entry, dict) or not isinstance(entry.get("is_mutating"), bool):
            problems.append(f"{name}: is_mutating must be true or false")
            continue
        params = entry.get("params")
        if params == UNCHECKED:
            continue
        if not isinstance(params, dict) or params.get("type") != "object":
            problems.append(f"{name}: params must be an object schema or \"{UNCHECKED}\"")
            continue
        for ref in re.findall(r'"\$ref": "([^"]+)"', json.dumps(params)):
            if not ref.startswith("#/$defs/") or ref[8:] not in defs:
                problems.append(f"{name}: unknown reference {ref}")
    return problems


def cs_const_name(command: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[._]", command) if part)


def build_python(data: dict) -> str:
    commands = {name: {"is_mutating": e["is_mutating"], "params": e["params"]} for name, e in data["commands"].items()}
    defs = pprint.pformat(data.get("$defs", {}), width=110, sort_dicts=False)
    cmds = pprint.pformat(commands, width=110, sort_dicts=False)
    return f'''"""Generated by scripts/gen_bridge_contract.py from contracts/bridge-commands.json. Do not edit.

Run `python scripts/gen_bridge_contract.py` after changing the contract.
"""
from __future__ import annotations

from typing import Any

from .contract_validate import validate_payload

CONTRACT_VERSION = {data["contract_version"]!r}
UNCHECKED = "unchecked"

DEFS: dict[str, Any] = {defs}

COMMANDS: dict[str, dict[str, Any]] = {cmds}


def is_mutating(name: str) -> bool | None:
    """True or False for a command in the contract, None for a command it does not list."""
    entry = COMMANDS.get(name)
    return None if entry is None else bool(entry["is_mutating"])


def is_checked(name: str) -> bool:
    """True when the contract has a payload schema for this command."""
    entry = COMMANDS.get(name)
    return entry is not None and entry["params"] != UNCHECKED


def validate_command(name: str, params: Any) -> None:
    """Raise BridgeContractError when params do not fit the command's schema.

    A command the contract does not list, or lists as "unchecked", passes unchanged.
    """
    entry = COMMANDS.get(name)
    if entry is None or entry["params"] == UNCHECKED:
        return
    validate_payload(name, entry["params"], params, DEFS)
'''


def build_csharp(data: dict) -> str:
    names = list(data["commands"])
    consts = [cs_const_name(n) for n in names]
    if len(set(consts)) != len(consts):
        raise SystemExit("Two commands map to the same C# constant name")
    width = max(len(c) for c in consts)
    lines = [
        "// <auto-generated>",
        "// Generated by scripts/gen_bridge_contract.py from contracts/bridge-commands.json. Do not edit.",
        "// </auto-generated>",
        "using System;",
        "using System.Collections.Generic;",
        "",
        "namespace RevitBridge.Bridge;",
        "",
        "/// <summary>Add-in command names and their IsMutating flags from the shared command contract.</summary>",
        "public static class BridgeContract",
        "{",
        f"    public const int ContractVersion = {int(data['contract_version'])};",
        "",
    ]
    for const, name in zip(consts, names):
        lines.append(f'    public const string {const.ljust(width)} = "{name}";')
    lines += [
        "",
        "    /// <summary>True when the command changes the model. Must agree with each [BridgeCommand] attribute.</summary>",
        "    public static readonly Dictionary<string, bool> IsMutating = new Dictionary<string, bool>(StringComparer.Ordinal)",
        "    {",
    ]
    for const, name in zip(consts, names):
        flag = "true" if data["commands"][name]["is_mutating"] else "false"
        lines.append(f"        {{ {(const + ',').ljust(width + 1)} {flag} }},")
    lines += ["    };", "}", ""]
    return "\n".join(lines)


def outputs(data: dict | None = None) -> dict[Path, str]:
    data = data or load()
    return {PY_OUT: build_python(data), CS_OUT: build_csharp(data)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is out of date")
    args = parser.parse_args(argv)
    stale = []
    for path, text in outputs().items():
        current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(ROOT).as_posix()}")
    if stale:
        print("Stale generated files: " + ", ".join(stale) + ". Run: python scripts/gen_bridge_contract.py")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
